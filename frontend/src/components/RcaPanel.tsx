import { useEffect, useState } from 'react'
import { RcaReport } from '../types'

const API_KEY = import.meta.env.VITE_API_KEY ?? 'dev-secret'

function RcaField({ label, value }: { label: string; value: string }) {
  if (!value) return null
  return (
    <div className="rounded-md border border-slate-200 bg-white p-3 dark:border-slate-700 dark:bg-slate-900">
      <div className="mb-1 text-xs font-semibold uppercase tracking-wide text-slate-500 dark:text-slate-400">
        {label}
      </div>
      <p className="whitespace-pre-wrap text-sm text-slate-800 dark:text-slate-100">{value}</p>
    </div>
  )
}

export function RcaPanel({ incidentId }: { incidentId: string | undefined }) {
  const [rca, setRca] = useState<RcaReport | null>(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    setRca(null)
    setError(null)
    if (!incidentId) return
    void (async () => {
      try {
        const res = await fetch(`/api/incidents/${incidentId}`, {
          headers: { 'X-API-Key': API_KEY },
        })
        if (!res.ok) return
        const data = (await res.json()) as { incident: unknown; rca_report?: RcaReport }
        if (data.rca_report) setRca(data.rca_report)
      } catch {
        // no existing RCA — that's fine
      }
    })()
  }, [incidentId])

  async function generate() {
    if (!incidentId) return
    setLoading(true)
    setError(null)
    try {
      const res = await fetch('/api/rca/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'X-API-Key': API_KEY },
        body: JSON.stringify({ incident_id: incidentId }),
      })
      if (!res.ok) throw new Error(`${res.status}`)
      const data = (await res.json()) as RcaReport
      setRca(data)
    } catch {
      setError('Failed to generate RCA. Try again.')
    } finally {
      setLoading(false)
    }
  }

  if (!incidentId) {
    return (
      <p className="text-sm text-slate-500 dark:text-slate-400">
        Select an incident to generate an RCA report.
      </p>
    )
  }

  return (
    <div className="flex flex-col gap-3">
      <button
        type="button"
        disabled={loading}
        onClick={() => void generate()}
        className="inline-flex w-full items-center justify-center gap-2 rounded-md bg-indigo-600 px-3 py-2 text-sm font-medium text-white hover:bg-indigo-700 disabled:opacity-50"
      >
        {loading ? (
          <>
            <span
              className="inline-block h-4 w-4 animate-spin rounded-full border-2 border-white border-t-transparent"
              aria-hidden
            />
            Generating…
          </>
        ) : rca ? (
          'Regenerate RCA'
        ) : (
          'Generate RCA'
        )}
      </button>

      {error ? (
        <p className="rounded-md bg-red-50 px-3 py-2 text-sm text-red-700 dark:bg-red-950/40 dark:text-red-300">
          {error}
        </p>
      ) : null}

      {rca ? (
        <div className="flex flex-col gap-2">
          <RcaField label="Timeline" value={rca.timeline} />
          <RcaField label="Root cause" value={rca.root_cause} />
          <RcaField label="Impacted systems" value={rca.impacted_systems} />
          <RcaField label="Resolution steps" value={rca.resolution_steps} />
          <RcaField label="Recommendations" value={rca.recommendations} />
          <p className="text-right text-xs text-slate-400 dark:text-slate-500">
            Generated by {rca.generated_by}
          </p>
        </div>
      ) : !loading ? (
        <p className="text-sm text-slate-500 dark:text-slate-400">
          No RCA report yet. Click the button above to generate one.
        </p>
      ) : null}
    </div>
  )
}
